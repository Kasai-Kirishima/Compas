import assert from 'node:assert/strict';
import { rotateGeometryObject, scaleGeometryObject, scaleObjectToBounds } from '../src/transforms.mjs';
const close = (a,b) => assert.ok(Math.abs(a-b)<1e-8, `${a} != ${b}`);
let line=rotateGeometryObject({type:'line',a:{x:0,y:0},b:{x:10,y:0}},90,{x:5,y:0});
close(line.a.x,5); close(line.a.y,-5); close(line.b.x,5); close(line.b.y,5); close(line.rotation,90);
let circle=rotateGeometryObject({type:'circle',center:{x:10,y:0},r:4},90,{x:0,y:0});
close(circle.center.x,0); close(circle.center.y,10); close(circle.r,4);
let ellipse=rotateGeometryObject({type:'ellipse',center:{x:4,y:8},rx:5,ry:2},45,{x:0,y:0});
close(ellipse.center.x,4*Math.SQRT1_2-8*Math.SQRT1_2); close(ellipse.rotation,45);
let rect=rotateGeometryObject({type:'rect',x:0,y:0,w:10,h:4},90,{x:5,y:2});
assert.equal(rect.type,'polygon'); assert.equal(rect.points.length,4); assert.equal('x' in rect,false); assert.equal('w' in rect,false); close(rect.rotation,90);
let text=rotateGeometryObject({type:'text',x:10,y:0,text:'A',size:3},90,{x:0,y:0});
close(text.x,0);close(text.y,10);close(text.rotation,90);
let arc=rotateGeometryObject({type:'arc',center:{x:0,y:0},r:5,startAngle:0,endAngle:90},30,{x:0,y:0});
close(arc.startAngle,30);close(arc.endAngle,120);
let reference=rotateGeometryObject({type:'reference',x:0,y:0,w:20,h:10,rotation:0},90,{x:0,y:0});
close(reference.rotation,90);close(reference.x,-15);close(reference.y,5);
const scaledCircle = scaleGeometryObject({type:'circle',center:{x:10,y:10},r:5},2,2);
close(scaledCircle.center.x,10); close(scaledCircle.center.y,10); close(scaledCircle.r,10);
const scaledRect = scaleGeometryObject({type:'rect',x:0,y:0,w:10,h:5},2,3,{x:0,y:0});
close(scaledRect.x,0); close(scaledRect.y,0); close(scaledRect.w,20); close(scaledRect.h,15);
const scaledLine = scaleGeometryObject({type:'line',a:{x:0,y:0},b:{x:10,y:5}},2,2,{x:0,y:0});
close(scaledLine.b.x,20); close(scaledLine.b.y,10);
const scaledText = scaleGeometryObject({type:'text',x:4,y:6,size:3},1.5,1.5);
close(scaledText.size,4.5);
const scaledReference = scaleGeometryObject({type:'reference',x:0,y:0,w:20,h:10,keepAspect:true},2,2,{x:0,y:0});
close(scaledReference.w,40); close(scaledReference.h,20);
const offsetCircle = scaleGeometryObject({type:'circle',center:{x:10,y:10},r:5,dx:20,dy:5},2,2);
close(offsetCircle.center.x,30); close(offsetCircle.center.y,15); close(offsetCircle.dx,0); close(offsetCircle.r,10);
const resizedCircle = scaleObjectToBounds({type:'circle',center:{x:10,y:10},r:10},{x:5,y:6,w:40,h:20});
close(resizedCircle.r,20); close(resizedCircle.center.x,25); close(resizedCircle.center.y,26);
const resizedCircleHeightOnly = scaleObjectToBounds({type:'circle',center:{x:10,y:10},r:10},{x:5,y:6,w:20,h:40});
close(resizedCircleHeightOnly.r,20); close(resizedCircleHeightOnly.center.x,25); close(resizedCircleHeightOnly.center.y,26);
const resizedEllipse = scaleObjectToBounds({type:'ellipse',center:{x:10,y:10},rx:5,ry:3},{x:0,y:0,w:20,h:18});
close(resizedEllipse.rx,10); close(resizedEllipse.ry,9);
const resizedHorizontalLine = scaleObjectToBounds({type:'line',a:{x:0,y:5},b:{x:10,y:5}},{x:2,y:5,w:30,h:0});
close(resizedHorizontalLine.a.x,2); close(resizedHorizontalLine.b.x,32);
const resizedRect = scaleObjectToBounds({type:'rect',x:0,y:0,w:10,h:5},{x:10,y:20,w:30,h:15});
close(resizedRect.x,10); close(resizedRect.y,20); close(resizedRect.w,30); close(resizedRect.h,15);
console.log('transforms: ok (rotation and object scaling/bounds editing for line, circle, ellipse, rect, text, arc, reference)');
