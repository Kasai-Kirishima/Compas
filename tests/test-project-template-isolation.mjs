import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import vm from 'node:vm';
const app=await readFile(new URL('../js/app.js',import.meta.url),'utf8');
const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const templateSource=await readFile(new URL('../js/template.js',import.meta.url),'utf8');
const pkg=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
const templates=await readdir(new URL('../templates/',import.meta.url));
assert.deepEqual(templates.sort(),['Lab4-A3-portrait-preview.png','Lab4-A3-portrait.svg','Lab5-A4-portrait-preview.png','Lab5-A4-portrait.svg','Lab5-GOST-A3-landscape-preview.png','Lab5-GOST-A3-landscape.svg','Lab5-GOST-A3-portrait-preview.png','Lab5-GOST-A3-portrait.svg','Lab8-A3-landscape-preview.png','Lab8-A3-landscape.svg','README.md','Technical-GOST-A3-landscape-preview.png','Technical-GOST-A3-landscape.svg','Technical-GOST-A3-portrait-preview.png','Technical-GOST-A3-portrait.svg']);
assert.match(app,/state\.format=doc\.format\|\|fixedFormatForTemplate\(state\.titleForm\)\|\|'A4P'/);
assert.equal((app.match(/state\.format=doc\.format\|\|fixedFormatForTemplate\(state\.titleForm\)\|\|'A4P'/g)||[]).length,2,'Import and autosave keep the stored page format before applying any template inference');
assert.match(app,/function emptyTitleValues\(\)/);
assert.match(app,/Object\.assign\(emptyTitleValues\(\),doc\.title&&typeof doc\.title==='object'\?doc\.title:\{\}\)/);
assert.ok(app.includes("$('literField').value=t.liter??''"));
assert.ok(app.includes("$('massField').value=t.mass??''"));
assert.match(app,/frozen\.schemaVersion===1&&frozen\.templateId===templateId&&frozen\.format===state\.format/);
assert.match(app,/templateSnapshot:deep\(state\.templateSnapshot\|\|null\)/);
assert.match(html,/id="developerField" value="Кушвид О\."/);
assert.match(app,/developer:'Кушвид О\.'/);
assert.match(app,/next\.developer='Кушвид О\.'/);
assert.equal(pkg.version,'1.5.45');
assert.ok(html.includes('data-template-preset="lab5-a4-reference-template"'));
assert.ok(html.includes('data-template-preset="lab5-gost-a3-portrait"'));
assert.ok(html.includes('data-template-preset="technical-gost-a3-landscape"'));
assert.doesNotMatch(html,/data-template-preset="form1"/);
const sandbox={window:{}};vm.runInNewContext(templateSource,sandbox,{filename:'js/template.js'});
const blank=sandbox.window.KompasTemplate.markup('A3P',{title:'',code:'',company:'',developer:'',checker:'',scale:'',sheets:''},'lab4-reference-template');
for(const bad of ['Кушвид О.','Базиль Б.','Лабораторна робота 4','КТ-24.ЛР4.001','Шосткинський фаховий коледж','1:1'])assert.ok(!blank.includes(bad),`Explicitly blank saved fields stay blank: ${bad}`);
const lab8=sandbox.window.KompasTemplate.markup('A3L',{title:'Корпус',code:'8.090220 АР ХХ ХХ 01',company:'ШЦМГУ'},'lab8-reference-template');
assert.ok(lab8.includes('Корпус')&&lab8.includes('Вариант 8')&&lab8.includes('ШЦМГУ'));
const legacyTechnical=sandbox.window.KompasTemplate.markup('A3P',{title:'Legacy'},'technical-a3-template');
assert.ok(!legacyTechnical.includes('Вариант 8'),'Old technical ID continues to use its former renderer and cannot be silently replaced by Lab 8');
console.log('Project/template isolation passed: seven catalog templates; legacy IDs and saved sheet data remain isolated.');
