import assert from 'node:assert/strict';
import {distance,snapToGrid,normalizeRect,boundsOf,isValidSheet} from '../src/geometry.mjs';
import {normalizeProject,PROJECT_VERSION} from '../src/project-schema.mjs';
assert.equal(distance({x:0,y:0},{x:3,y:4}),5);
assert.deepEqual(snapToGrid({x:7.2,y:12.4},5),{x:5,y:10});
assert.deepEqual(normalizeRect({x:8,y:9},{x:2,y:3}),{x:2,y:3,w:6,h:6});
assert.deepEqual(boundsOf([{x:2,y:5},{x:8,y:1}]),{x:2,y:1,w:6,h:4});
assert.equal(isValidSheet(420,297),true); assert.equal(isValidSheet(-1,297),false);
const p=normalizeProject({width:420,height:297,objects:[{type:'line'}]});
assert.equal(p.version,PROJECT_VERSION);assert.equal(p.objects.length,1);
assert.throws(()=>normalizeProject({width:-1,height:10}));
console.log('CAD core checks passed (8 assertions).');
