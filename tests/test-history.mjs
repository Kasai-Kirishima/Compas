import assert from 'node:assert/strict';
import { Line, Circle, serializeScene } from '../src/cad-geometry-trim.mjs';
import { SceneHistory } from '../src/history.mjs';
const a = new Line({x:0,y:0},{x:10,y:0});
const h = new SceneHistory([a], {limit:2});
assert.equal(h.scene.length,1); assert.equal(h.canUndo,false);
h.replace([a,new Circle({x:0,y:0},5)]); assert.equal(h.scene.length,2);
h.undo(); assert.equal(h.scene.length,1); h.redo(); assert.equal(h.scene.length,2);
const snapshot = h.snapshot(); h.replace([]); h.restore(snapshot); assert.equal(h.scene.length,2);
h.clear(); assert.equal(h.canUndo,false); assert.equal(h.canRedo,false);
const limited = new SceneHistory([],{limit:2});
limited.replace([a]); limited.replace([]); limited.replace([a]);
assert.equal(limited.undoCount,2);
console.log('All scene history tests passed.');
